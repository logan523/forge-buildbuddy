/**
 * Export classroom lab packs (plan + LAB.md + mcp snippet + task checklist).
 *
 *   npm run classroom:export
 *   → classroom/labs/lab-sat-line/
 */

import { mkdirSync, writeFileSync, copyFileSync, existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CLASSROOM_LABS } from "../src/lib/classroom/catalog.ts";
import { applyTrustPipeline } from "../src/lib/trust.ts";
import { runTask } from "../src/lib/tasks/run.ts";
import { exportKitAgentPack, kitAgentPackFiles } from "../src/lib/kits/export-agent.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outRoot = path.resolve(process.argv[2] || path.join(ROOT, "classroom", "labs"));

let failed = 0;

for (const lab of CLASSROOM_LABS) {
  const labDir = path.join(outRoot, lab.id);
  mkdirSync(labDir, { recursive: true });

  const planSrc = path.join(ROOT, lab.planPath);
  if (!existsSync(planSrc)) {
    console.error(`Missing plan for ${lab.id}: ${lab.planPath}`);
    failed++;
    continue;
  }
  copyFileSync(planSrc, path.join(labDir, "plan.json"));

  const raw = JSON.parse(readFileSync(planSrc, "utf8"));
  const plan = applyTrustPipeline(JSON.parse(JSON.stringify(raw)));

  // Gate: listed tasks must pass
  const reports = lab.taskIds.map((id) => runTask(id, plan));
  const bad = reports.filter((r) => !r.pass);
  if (bad.length) {
    console.error(`${lab.id}: ${bad.length} task(s) failed`);
    for (const r of bad) {
      console.error(`  ${r.taskId}: ${r.checks.filter((c) => !c.pass).map((c) => c.detail).join("; ")}`);
    }
    failed++;
  }

  const pack = exportKitAgentPack(plan, { authorName: "Forge Classroom" });
  for (const f of kitAgentPackFiles(plan, pack)) {
    writeFileSync(path.join(labDir, f.filename), f.content, "utf8");
  }

  const labMd = [
    `# Lab: ${lab.title}`,
    "",
    lab.brief,
    "",
    `**Time:** ~${lab.estimatedMinutes} minutes`,
    "",
    "## Setup",
    "",
    "1. Open Forge: `npm run dev`",
    "2. Load the Sat Line demo (or set `FORGE_PLAN` to this folder's `plan.json`)",
    "3. Optional MCP:",
    "   ```bash",
    `   FORGE_PLAN=${path.relative(ROOT, path.join(labDir, "plan.json"))} npm run mcp:server`,
    "   ```",
    "4. Install skills (subset):",
    "   ```bash",
    ...lab.skillIds.map((id) => `   cp -r agent-skills/forge/${id} ~/.claude/skills/`),
    "   ```",
    "",
    "## Offline gates (must pass before lab credit)",
    "",
    "```bash",
    "npm run audit:tasks",
    "```",
    "",
    "| Task | Title | Status |",
    "|------|-------|--------|",
    ...reports.map((r) => `| ${r.taskId} | ${r.title} | ${r.pass ? "ready" : "FAIL"} |`),
    "",
    "## In-lab",
    "",
    "1. Prep + safety ack",
    "2. Complete wiring steps (isolated 3D stage)",
    "3. Flash diag firmware; confirm I2C devices",
    "4. Celebrate only after bus verify or honest skip",
    "",
    "## Files in this pack",
    "",
    "- `plan.json` — BuildPlan",
    "- `forge-kit-*-SKILL.md` — agent skill for this lab",
    "- agent pack JSON/YAML companions",
    "",
  ].join("\n");

  writeFileSync(path.join(labDir, "LAB.md"), labMd, "utf8");

  const rubric = [
    `# Instructor rubric — ${lab.title}`,
    "",
    "## Offline (required for credit)",
    "",
    "| Criterion | Evidence | Pass |",
    "|-----------|----------|------|",
    "| `npm run audit:tasks` green | CI or student screenshot | ☐ |",
    ...lab.taskIds.map((id) => `| Task ${id} | Task explorer report | ☐ |`),
    "",
    "## In-lab",
    "",
    "| Criterion | Evidence | Pass |",
    "|-----------|----------|------|",
    "| Safety ack completed | Prep screen | ☐ |",
    "| Wiring steps use isolated 3D (not full product only) | Spot check | ☐ |",
    "| Connections table colors match jumpers | Spot check SDA blue / SCL yellow | ☐ |",
    "| Flash path attempted OR documented skip | Serial drawer / notes | ☐ |",
    "| Live I2C verify passed OR honest skip | End-of-build gate | ☐ |",
    "",
    "## Integrity",
    "",
    "- Do **not** award credit if steps invent ordinal pin positions.",
    "- Soft-skip of bus verify is allowed without hardware; note it on the sheet.",
    "- ERC errors → kit publish blocked (students must not share broken recipes).",
    "",
    `Estimated lab time: ~${lab.estimatedMinutes} minutes.`,
    "",
  ].join("\n");
  writeFileSync(path.join(labDir, "RUBRIC.md"), rubric, "utf8");

  writeFileSync(
    path.join(labDir, "mcp.env.example"),
    `# Point Forge MCP at this lab's plan\nFORGE_PLAN=${path.join(labDir, "plan.json")}\n`,
    "utf8"
  );

  console.log(`✓ ${lab.id} → ${labDir}${bad.length ? " (TASKS FAILED)" : ""}`);
}

const index = [
  "# Forge classroom labs",
  "",
  "Generated by `npm run classroom:export`.",
  "",
  "| Lab | Title | Minutes |",
  "|-----|-------|---------|",
  ...CLASSROOM_LABS.map((l) => `| [\`${l.id}\`](./${l.id}/LAB.md) | ${l.title} | ${l.estimatedMinutes} |`),
  "",
  "## Instructor",
  "",
  "1. `npm run skills:export && npm run classroom:export`",
  "2. Students clone repo or receive a lab folder",
  "3. Credit = offline `audit:tasks` green + in-lab live verify (or documented skip)",
  "",
].join("\n");

mkdirSync(outRoot, { recursive: true });
writeFileSync(path.join(outRoot, "README.md"), index, "utf8");

if (failed) {
  console.error(`\nClassroom export finished with ${failed} failure(s).`);
  process.exit(1);
}
console.log(`\nClassroom packs ready under ${outRoot}`);
