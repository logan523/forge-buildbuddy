// Rotation speed: one full 8-frame spin every ~16s — slow enough to read as
// a globe turning, not spinning like a fan.
const unsigned long EARTH_ROTATION_FRAME_MS = 2000UL;

// A rocket orbiting the globe, reusing the same sprites from
// mars-and-back.h — every ROCKET_ORBIT_INTERVAL_MS (loop() controls the
// timer) one full lap plays, then it's gone until the next minute mark.
// Orbit radius is bigger than the globe (52px, so radius 26) plus the
// rocket's own half-width, so it clears the sphere with a visible gap
// rather than clipping across it. Centered on the globe, so the bottom-
// right arc naturally runs off-screen — Adafruit_GFX clips out-of-bounds
// pixels safely, so that reads as "behind the globe," not a bug.
const int ORBIT_CX = EARTH_GLOBE_X + EARTH_GLOBE_D / 2;
const int ORBIT_CY = EARTH_GLOBE_Y + EARTH_GLOBE_D / 2;
const int ORBIT_RX = 36, ORBIT_RY = 32;
const unsigned long ROCKET_ORBIT_DURATION_MS = 4000UL;  // one full lap

void drawRocketOrbit(unsigned long elapsed) {
  float angle = (elapsed / (float)ROCKET_ORBIT_DURATION_MS) * 2.0f * PI;
  int rx = ORBIT_CX + (int)(ORBIT_RX * cos(angle));
  int ry = ORBIT_CY - (int)(ORBIT_RY * sin(angle));
  int flameFrame = (int)((elapsed / 150) % 2);
  // Sprite matches actual direction of travel (derivative of x w.r.t.
  // angle) so it flips exactly when the path reverses horizontally, not on
  // a hand-picked top/bottom split.
  bool movingLeft = sin(angle) > 0;
  const unsigned char* const* frames = movingLeft ? rocket_left_frames : rocket_right_frames;
  display.drawBitmap(rx - 8, ry - 8, frames[flameFrame], 16, 16, SSD1306_WHITE);
}

// The live clock face: big rotating globe bottom-right, time/date/readings
// stacked in the column to its left. Uses the fonts already set up in
// weather-clock.ino (FreeSansBold12pt7b / FreeSans9pt7b) for the time; the
// default font for the rest, sized to reliably fit the narrower column.
// `timeStr` is 12-hour with no leading zero (e.g. "2:32"); `ampm` prints
// small, right after it on the same line — the default-font "AM"/"PM" is
// only 12px wide, comfortably inside the ~15px left over from the widest
// possible time text ("11:11") before hitting the globe's left edge.
void drawWorldMapClockFace(bool haveTime, const char* timeStr, const char* dateStr, const char* ampm, float inT, float inH, float outT, const String& outC) {
  int frame = (int)((millis() / EARTH_ROTATION_FRAME_MS) % EARTH_GLOBE_FRAME_COUNT);
  display.drawBitmap(EARTH_GLOBE_X, EARTH_GLOBE_Y, earth_globe_frames[frame], EARTH_GLOBE_D, EARTH_GLOBE_D, SSD1306_WHITE);

  if (haveTime) {
    display.setFont(&FreeSansBold12pt7b);
    display.setCursor(0, 15);
    display.print(timeStr);
    display.setFont(NULL);
    display.setCursor(display.getCursorX() + 1, 8);
    display.print(ampm);
    display.setCursor(0, 22);
    display.print(dateStr);
  } else {
    display.setFont(NULL);
    display.setCursor(0, 0);
    display.print("Syncing...");
  }

  display.setCursor(0, 38);
  display.print("In  "); display.print(inT, 0); display.print("F "); display.print(inH, 0); display.print("%");
  display.setCursor(0, 48);
  display.print("Out "); display.print(outT, 0); display.print("F"); display.println();
  display.setCursor(0, 56);
  display.print(outC);
}
